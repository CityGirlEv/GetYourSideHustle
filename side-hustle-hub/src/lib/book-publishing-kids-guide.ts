/** Parent-managed storybook profit. Unique key: storybookDirectPrintedCopiesSold. */
export function computeBookPublishingKidsProfit(input: {
  storybookDirectPrintedCopiesSold?: number;
  averageDirectSalePrice?: number;
  ebookSales?: number;
  averageActualEbookRoyaltyPerSale?: number;
  printOnDemandSales?: number;
  averageActualPrintRoyaltyPerSale?: number;
  otherEarnedBookIncome?: number;
  proofCopies?: number;
  directSaleInventoryPrinting?: number;
  artSupplies?: number;
  softwareLicensedAssets?: number;
  eventBoothFees?: number;
  packagingShipping?: number;
  paymentFees?: number;
  advertisingPrinting?: number;
  otherExpenses?: number;
  writingRevisionHours?: number;
  illustrationHours?: number;
  layoutProofingHours?: number;
  publishingMarketingSalesAdminHours?: number;
}): {
  directSaleRevenue: number;
  ebookRoyalties: number;
  printRoyalties: number;
  totalEarnedRevenue: number;
  totalExpenses: number;
  estimatedProfit: number;
  totalHours: number;
  profitPerHour: number | null;
  profitMarginPercent: number;
} {
  const directSaleRevenue =
    Math.max(0, Number(input.storybookDirectPrintedCopiesSold) || 0) *
    Math.max(0, Number(input.averageDirectSalePrice) || 0);
  const ebookRoyalties =
    Math.max(0, Number(input.ebookSales) || 0) *
    Math.max(0, Number(input.averageActualEbookRoyaltyPerSale) || 0);
  const printRoyalties =
    Math.max(0, Number(input.printOnDemandSales) || 0) *
    Math.max(0, Number(input.averageActualPrintRoyaltyPerSale) || 0);
  const other = Math.max(0, Number(input.otherEarnedBookIncome) || 0);
  const totalEarnedRevenue = directSaleRevenue + ebookRoyalties + printRoyalties + other;
  const totalExpenses =
    Math.max(0, Number(input.proofCopies) || 0) +
    Math.max(0, Number(input.directSaleInventoryPrinting) || 0) +
    Math.max(0, Number(input.artSupplies) || 0) +
    Math.max(0, Number(input.softwareLicensedAssets) || 0) +
    Math.max(0, Number(input.eventBoothFees) || 0) +
    Math.max(0, Number(input.packagingShipping) || 0) +
    Math.max(0, Number(input.paymentFees) || 0) +
    Math.max(0, Number(input.advertisingPrinting) || 0) +
    Math.max(0, Number(input.otherExpenses) || 0);
  const estimatedProfit = totalEarnedRevenue - totalExpenses;
  const totalHours =
    Math.max(0, Number(input.writingRevisionHours) || 0) +
    Math.max(0, Number(input.illustrationHours) || 0) +
    Math.max(0, Number(input.layoutProofingHours) || 0) +
    Math.max(0, Number(input.publishingMarketingSalesAdminHours) || 0);
  return {
    directSaleRevenue,
    ebookRoyalties,
    printRoyalties,
    totalEarnedRevenue,
    totalExpenses,
    estimatedProfit,
    totalHours,
    profitPerHour: totalHours > 0 ? estimatedProfit / totalHours : null,
    profitMarginPercent: totalEarnedRevenue > 0 ? (estimatedProfit / totalEarnedRevenue) * 100 : 0,
  };
}
