export function computeUgcCreatorProfit(input: {
  ugcVideosDelivered?: number;
  averageProductionFee?: number;
  usageRightsRevenue?: number;
  rawFootageAddOnRevenue?: number;
  whitelistingExclusivityRevenue?: number;
  otherEarnedIncome?: number;
  productsPropsNotReimbursed?: number;
  equipmentSoftwareAssets?: number;
  shippingTravel?: number;
  paymentFees?: number;
  insuranceProfessionalServices?: number;
  otherExpenses?: number;
  salesBriefsHours?: number;
  conceptScriptHours?: number;
  filmingHours?: number;
  editingHours?: number;
  revisionsDeliveryAdminHours?: number;
}): {
  baseProductionRevenue: number;
  grossServiceRevenue: number;
  totalExpenses: number;
  estimatedProfit: number;
  totalHours: number;
  profitPerHour: number | null;
  profitMarginPercent: number;
} {
  const baseProductionRevenue =
    Math.max(0, Number(input.ugcVideosDelivered) || 0) *
    Math.max(0, Number(input.averageProductionFee) || 0);
  const grossServiceRevenue =
    baseProductionRevenue +
    Math.max(0, Number(input.usageRightsRevenue) || 0) +
    Math.max(0, Number(input.rawFootageAddOnRevenue) || 0) +
    Math.max(0, Number(input.whitelistingExclusivityRevenue) || 0) +
    Math.max(0, Number(input.otherEarnedIncome) || 0);
  const totalExpenses =
    Math.max(0, Number(input.productsPropsNotReimbursed) || 0) +
    Math.max(0, Number(input.equipmentSoftwareAssets) || 0) +
    Math.max(0, Number(input.shippingTravel) || 0) +
    Math.max(0, Number(input.paymentFees) || 0) +
    Math.max(0, Number(input.insuranceProfessionalServices) || 0) +
    Math.max(0, Number(input.otherExpenses) || 0);
  const estimatedProfit = grossServiceRevenue - totalExpenses;
  const totalHours =
    Math.max(0, Number(input.salesBriefsHours) || 0) +
    Math.max(0, Number(input.conceptScriptHours) || 0) +
    Math.max(0, Number(input.filmingHours) || 0) +
    Math.max(0, Number(input.editingHours) || 0) +
    Math.max(0, Number(input.revisionsDeliveryAdminHours) || 0);
  return {
    baseProductionRevenue,
    grossServiceRevenue,
    totalExpenses,
    estimatedProfit,
    totalHours,
    profitPerHour: totalHours > 0 ? estimatedProfit / totalHours : null,
    profitMarginPercent: grossServiceRevenue > 0 ? (estimatedProfit / grossServiceRevenue) * 100 : 0,
  };
}
