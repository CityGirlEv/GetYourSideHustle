export function computeSocialInfluencerProfit(input: {
  sponsoredCampaignRevenue?: number;
  affiliateCommissionsCollected?: number;
  platformMonetizationCollected?: number;
  productGrossRevenue?: number;
  serviceSubscriptionRevenue?: number;
  licensingOtherEarnedIncome?: number;
  productCostFulfillmentRefunds?: number;
  platformPaymentAffiliateReversals?: number;
  equipmentSoftwareAssets?: number;
  contractors?: number;
  advertising?: number;
  travelPropsSamples?: number;
  insuranceLegalAccounting?: number;
  phoneInternetWebsite?: number;
  otherExpenses?: number;
  planningResearchHours?: number;
  productionEditingHours?: number;
  publishingCommunityHours?: number;
  brandSalesNegotiationHours?: number;
  reportingAdminSupportHours?: number;
}): {
  grossServiceRevenue: number;
  totalExpenses: number;
  estimatedProfit: number;
  totalHours: number;
  profitPerHour: number | null;
  profitMarginPercent: number;
} {
  const grossServiceRevenue =
    Math.max(0, Number(input.sponsoredCampaignRevenue) || 0) +
    Math.max(0, Number(input.affiliateCommissionsCollected) || 0) +
    Math.max(0, Number(input.platformMonetizationCollected) || 0) +
    Math.max(0, Number(input.productGrossRevenue) || 0) +
    Math.max(0, Number(input.serviceSubscriptionRevenue) || 0) +
    Math.max(0, Number(input.licensingOtherEarnedIncome) || 0);
  const totalExpenses =
    Math.max(0, Number(input.productCostFulfillmentRefunds) || 0) +
    Math.max(0, Number(input.platformPaymentAffiliateReversals) || 0) +
    Math.max(0, Number(input.equipmentSoftwareAssets) || 0) +
    Math.max(0, Number(input.contractors) || 0) +
    Math.max(0, Number(input.advertising) || 0) +
    Math.max(0, Number(input.travelPropsSamples) || 0) +
    Math.max(0, Number(input.insuranceLegalAccounting) || 0) +
    Math.max(0, Number(input.phoneInternetWebsite) || 0) +
    Math.max(0, Number(input.otherExpenses) || 0);
  const estimatedProfit = grossServiceRevenue - totalExpenses;
  const totalHours =
    Math.max(0, Number(input.planningResearchHours) || 0) +
    Math.max(0, Number(input.productionEditingHours) || 0) +
    Math.max(0, Number(input.publishingCommunityHours) || 0) +
    Math.max(0, Number(input.brandSalesNegotiationHours) || 0) +
    Math.max(0, Number(input.reportingAdminSupportHours) || 0);
  return {
    grossServiceRevenue,
    totalExpenses,
    estimatedProfit,
    totalHours,
    profitPerHour: totalHours > 0 ? estimatedProfit / totalHours : null,
    profitMarginPercent: grossServiceRevenue > 0 ? (estimatedProfit / grossServiceRevenue) * 100 : 0,
  };
}
