export function computeCommunityNewsletterProfit(input: {
  newsletterIssuesPerMonth?: number;
  averageFeePerIssue?: number;
  templateSetupRevenue?: number;
  interviewResearchAddOns?: number;
  emailDistributionRevenue?: number;
  printReadyRevenue?: number;
  sponsorAdServiceRevenue?: number;
  otherEarnedNewsletterIncome?: number;
  phoneInternet?: number;
  writingDesignEmailSoftware?: number;
  domainWebsiteStorage?: number;
  licensedAssets?: number;
  unreimbursedPrintingPostage?: number;
  paymentFees?: number;
  advertisingNetworking?: number;
  travelParking?: number;
  officeEquipment?: number;
  otherExpenses?: number;
  contentCollectionHours?: number;
  researchInterviewHours?: number;
  writingEditingHours?: number;
  designFormattingHours?: number;
  proofingRevisionHours?: number;
  emailDistributionHours?: number;
  marketingAdminHours?: number;
}): {
  monthlyIssueRevenue: number;
  grossServiceRevenue: number;
  totalExpenses: number;
  estimatedProfit: number;
  totalHours: number;
  profitPerHour: number | null;
  profitMarginPercent: number;
} {
  const monthlyIssueRevenue =
    Math.max(0, Number(input.newsletterIssuesPerMonth) || 0) *
    Math.max(0, Number(input.averageFeePerIssue) || 0);
  const grossServiceRevenue =
    monthlyIssueRevenue +
    Math.max(0, Number(input.templateSetupRevenue) || 0) +
    Math.max(0, Number(input.interviewResearchAddOns) || 0) +
    Math.max(0, Number(input.emailDistributionRevenue) || 0) +
    Math.max(0, Number(input.printReadyRevenue) || 0) +
    Math.max(0, Number(input.sponsorAdServiceRevenue) || 0) +
    Math.max(0, Number(input.otherEarnedNewsletterIncome) || 0);
  const totalExpenses =
    Math.max(0, Number(input.phoneInternet) || 0) +
    Math.max(0, Number(input.writingDesignEmailSoftware) || 0) +
    Math.max(0, Number(input.domainWebsiteStorage) || 0) +
    Math.max(0, Number(input.licensedAssets) || 0) +
    Math.max(0, Number(input.unreimbursedPrintingPostage) || 0) +
    Math.max(0, Number(input.paymentFees) || 0) +
    Math.max(0, Number(input.advertisingNetworking) || 0) +
    Math.max(0, Number(input.travelParking) || 0) +
    Math.max(0, Number(input.officeEquipment) || 0) +
    Math.max(0, Number(input.otherExpenses) || 0);
  const estimatedProfit = grossServiceRevenue - totalExpenses;
  const totalHours =
    Math.max(0, Number(input.contentCollectionHours) || 0) +
    Math.max(0, Number(input.researchInterviewHours) || 0) +
    Math.max(0, Number(input.writingEditingHours) || 0) +
    Math.max(0, Number(input.designFormattingHours) || 0) +
    Math.max(0, Number(input.proofingRevisionHours) || 0) +
    Math.max(0, Number(input.emailDistributionHours) || 0) +
    Math.max(0, Number(input.marketingAdminHours) || 0);
  return {
    monthlyIssueRevenue,
    grossServiceRevenue,
    totalExpenses,
    estimatedProfit,
    totalHours,
    profitPerHour: totalHours > 0 ? estimatedProfit / totalHours : null,
    profitMarginPercent: grossServiceRevenue > 0 ? (estimatedProfit / grossServiceRevenue) * 100 : 0,
  };
}
