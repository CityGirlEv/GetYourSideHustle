export function computePartTimeNotaryProfit(input: {
  notaryAppointmentsPerMonth?: number;
  averageLawfulNotarialFeesPerAppointment?: number;
  permittedTravelConvenienceFees?: number;
  contractedSigningServiceRevenue?: number;
  authorizedRemoteElectronicRevenue?: number;
  otherLawfulEarnedIncome?: number;
  commissionRenewalAllocation?: number;
  bondInsuranceAllocation?: number;
  sealJournalCertificates?: number;
  trainingBackgroundScreening?: number;
  remotePlatformTechnology?: number;
  printingScanningShipping?: number;
  mileageParkingTolls?: number;
  phoneInternet?: number;
  paymentFeesAdvertising?: number;
  otherExpenses?: number;
  appointmentHours?: number;
  travelWaitingHours?: number;
  printingPreparationHours?: number;
  recordsShippingHours?: number;
  marketingAdminTrainingHours?: number;
}): {
  monthlyNotarialRevenue: number;
  grossServiceRevenue: number;
  totalExpenses: number;
  estimatedProfit: number;
  totalHours: number;
  profitPerHour: number | null;
  profitMarginPercent: number;
} {
  const monthlyNotarialRevenue =
    Math.max(0, Number(input.notaryAppointmentsPerMonth) || 0) *
    Math.max(0, Number(input.averageLawfulNotarialFeesPerAppointment) || 0);
  const grossServiceRevenue =
    monthlyNotarialRevenue +
    Math.max(0, Number(input.permittedTravelConvenienceFees) || 0) +
    Math.max(0, Number(input.contractedSigningServiceRevenue) || 0) +
    Math.max(0, Number(input.authorizedRemoteElectronicRevenue) || 0) +
    Math.max(0, Number(input.otherLawfulEarnedIncome) || 0);
  const totalExpenses =
    Math.max(0, Number(input.commissionRenewalAllocation) || 0) +
    Math.max(0, Number(input.bondInsuranceAllocation) || 0) +
    Math.max(0, Number(input.sealJournalCertificates) || 0) +
    Math.max(0, Number(input.trainingBackgroundScreening) || 0) +
    Math.max(0, Number(input.remotePlatformTechnology) || 0) +
    Math.max(0, Number(input.printingScanningShipping) || 0) +
    Math.max(0, Number(input.mileageParkingTolls) || 0) +
    Math.max(0, Number(input.phoneInternet) || 0) +
    Math.max(0, Number(input.paymentFeesAdvertising) || 0) +
    Math.max(0, Number(input.otherExpenses) || 0);
  const estimatedProfit = grossServiceRevenue - totalExpenses;
  const totalHours =
    Math.max(0, Number(input.appointmentHours) || 0) +
    Math.max(0, Number(input.travelWaitingHours) || 0) +
    Math.max(0, Number(input.printingPreparationHours) || 0) +
    Math.max(0, Number(input.recordsShippingHours) || 0) +
    Math.max(0, Number(input.marketingAdminTrainingHours) || 0);
  return {
    monthlyNotarialRevenue,
    grossServiceRevenue,
    totalExpenses,
    estimatedProfit,
    totalHours,
    profitPerHour: totalHours > 0 ? estimatedProfit / totalHours : null,
    profitMarginPercent: grossServiceRevenue > 0 ? (estimatedProfit / grossServiceRevenue) * 100 : 0,
  };
}
