export function computeGoogleBusinessProfileHelperProfit(input: {
  gbpSmallProjectsCompleted?: number;
  averageSmallProjectFee?: number;
  setupCleanupRevenue?: number;
  monthlyMaintenanceRevenue?: number;
  photoPostAddOnRevenue?: number;
  otherEarnedIncome?: number;
  phoneInternet?: number;
  softwareStorage?: number;
  travelParking?: number;
  equipmentAllocation?: number;
  paymentFees?: number;
  advertisingNetworking?: number;
  insuranceProfessionalServices?: number;
  otherExpenses?: number;
  salesIntakeHours?: number;
  eligibilityOwnershipResearchHours?: number;
  auditPreparationHours?: number;
  editingContentHours?: number;
  approvalRevisionHours?: number;
  handoffReportingHours?: number;
  marketingAdminHours?: number;
}): {
  smallProjectRevenue: number;
  grossServiceRevenue: number;
  totalExpenses: number;
  estimatedProfit: number;
  totalHours: number;
  profitPerHour: number | null;
  profitMarginPercent: number;
} {
  const smallProjectRevenue =
    Math.max(0, Number(input.gbpSmallProjectsCompleted) || 0) *
    Math.max(0, Number(input.averageSmallProjectFee) || 0);
  const grossServiceRevenue =
    smallProjectRevenue +
    Math.max(0, Number(input.setupCleanupRevenue) || 0) +
    Math.max(0, Number(input.monthlyMaintenanceRevenue) || 0) +
    Math.max(0, Number(input.photoPostAddOnRevenue) || 0) +
    Math.max(0, Number(input.otherEarnedIncome) || 0);
  const totalExpenses =
    Math.max(0, Number(input.phoneInternet) || 0) +
    Math.max(0, Number(input.softwareStorage) || 0) +
    Math.max(0, Number(input.travelParking) || 0) +
    Math.max(0, Number(input.equipmentAllocation) || 0) +
    Math.max(0, Number(input.paymentFees) || 0) +
    Math.max(0, Number(input.advertisingNetworking) || 0) +
    Math.max(0, Number(input.insuranceProfessionalServices) || 0) +
    Math.max(0, Number(input.otherExpenses) || 0);
  const estimatedProfit = grossServiceRevenue - totalExpenses;
  const totalHours =
    Math.max(0, Number(input.salesIntakeHours) || 0) +
    Math.max(0, Number(input.eligibilityOwnershipResearchHours) || 0) +
    Math.max(0, Number(input.auditPreparationHours) || 0) +
    Math.max(0, Number(input.editingContentHours) || 0) +
    Math.max(0, Number(input.approvalRevisionHours) || 0) +
    Math.max(0, Number(input.handoffReportingHours) || 0) +
    Math.max(0, Number(input.marketingAdminHours) || 0);
  return {
    smallProjectRevenue,
    grossServiceRevenue,
    totalExpenses,
    estimatedProfit,
    totalHours,
    profitPerHour: totalHours > 0 ? estimatedProfit / totalHours : null,
    profitMarginPercent: grossServiceRevenue > 0 ? (estimatedProfit / grossServiceRevenue) * 100 : 0,
  };
}
