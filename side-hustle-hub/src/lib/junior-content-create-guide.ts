export function computeJuniorContentCreateProfit(input: {
  singlePiecesPerMonth?: number;
  avgPricePerSinglePiece?: number;
  threePostPacksPerMonth?: number;
  avgPricePerPack?: number;
  otherApprovedCreativeRevenue?: number;
  designAppCosts?: number;
  propsPrinting?: number;
  paymentFees?: number;
  otherBusinessExpenses?: number;
  totalHours?: number;
}): {
  singlePieceRevenue: number;
  packRevenue: number;
  monthlyRevenue: number;
  monthlyExpenses: number;
  estimatedMonthlyProfit: number;
  totalHours: number;
  effectiveProfitPerHour: number | null;
  profitMarginPercent: number;
} {
  const n = (v?: number) => Math.max(0, Number(v) || 0);
  const singlePieceRevenue = n(input.singlePiecesPerMonth) * n(input.avgPricePerSinglePiece);
  const packRevenue = n(input.threePostPacksPerMonth) * n(input.avgPricePerPack);
  const monthlyRevenue =
    singlePieceRevenue + packRevenue + n(input.otherApprovedCreativeRevenue);
  const monthlyExpenses =
    n(input.designAppCosts) +
    n(input.propsPrinting) +
    n(input.paymentFees) +
    n(input.otherBusinessExpenses);
  const estimatedMonthlyProfit = monthlyRevenue - monthlyExpenses;
  const totalHours = n(input.totalHours);
  return {
    singlePieceRevenue,
    packRevenue,
    monthlyRevenue,
    monthlyExpenses,
    estimatedMonthlyProfit,
    totalHours,
    effectiveProfitPerHour: totalHours > 0 ? estimatedMonthlyProfit / totalHours : null,
    profitMarginPercent: monthlyRevenue > 0 ? (estimatedMonthlyProfit / monthlyRevenue) * 100 : 0,
  };
}
