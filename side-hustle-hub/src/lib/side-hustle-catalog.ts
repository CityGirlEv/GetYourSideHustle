/**
 * AI hustles default to Pro/Elite. Small exceptions can be Free or Starter.
 */
/** Reserved — no Free AI hustles right now (coffee chat is Starter). */
export const AI_SIDE_HUSTLE_FREE_IDS = [] as const;

/** Peer coffee-chat teaching unlocks with Starter Membership (Adult/Senior). Kids/Teens treat AI as Elite. */
export const AI_SIDE_HUSTLE_STARTER_IDS = ["ai-peers"] as const;

/** Reserved — simpler AI helpers moved to Elite with Digital/AI policy. */
export const AI_SIDE_HUSTLE_PRO_IDS = [] as const;

export const AI_SIDE_HUSTLE_ELITE_IDS = [
  "ai-assets",
  "ai-timing",
  "ai-agents",
  "ai-promo-video",
  "create-games-kids",
  "create-games-junior",
  "ai-social-helper",
  "ai-prompt-helper",
  "local-business-ai-setup",
] as const;

export function isAiSideHustleId(id: string): boolean {
  return (
    (AI_SIDE_HUSTLE_FREE_IDS as readonly string[]).includes(id) ||
    (AI_SIDE_HUSTLE_STARTER_IDS as readonly string[]).includes(id) ||
    (AI_SIDE_HUSTLE_PRO_IDS as readonly string[]).includes(id) ||
    (AI_SIDE_HUSTLE_ELITE_IDS as readonly string[]).includes(id) ||
    id.startsWith("ai-") ||
    id.includes("-ai-") ||
    id.endsWith("-ai")
  );
}

export function isAiSideHustle(h: Pick<SideHustleRecord, "id" | "name" | "category" | "description">): boolean {
  if (isAiSideHustleId(h.id)) return true;
  if (/\bAI\b/.test(h.name) || /ChatGPT/i.test(h.name)) return true;
  if (/^AI\b|AI\s*\//i.test(h.category || "")) return true;
  return false;
}

