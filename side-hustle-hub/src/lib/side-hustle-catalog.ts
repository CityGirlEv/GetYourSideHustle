export function kidsScoreEntries(mode: "kids" | "junior") {
  return hustlesForAudience(mode).map((h) => {
    const interests = new Set<"animals" | "creative" | "outdoors" | "helping" | "tech" | "ai">();
    for (const t of h.matchTags) {
      if (t === "animals" || t === "creative" || t === "outdoors" || t === "helping" || t === "tech" || t === "ai") {
        interests.add(t);
      }
      if (t === "physical") interests.add("outdoors");
      if (t === "people") interests.add("helping");
    }
    if (interests.size === 0) interests.add("helping");
    const place = new Set<"outdoor" | "indoor" | "either">();
    if (h.locationMode === "local") place.add("outdoor");
    else if (h.locationMode === "online") place.add("indoor");
    else {
      place.add("either");
      place.add("indoor");
    }
    const tags = h.tags ?? {
      ages: mode === "kids" ? (["young", "mid", "older"] as const) : (["mid", "older"] as const),
      interests: [...interests],
      place: [...place],
      time: ["short", "medium"] as const,
    };
    return {
      id: h.id,
      audiences: h.audiences.filter((a): a is "kids" | "junior" => a === "kids" || a === "junior"),
      tags: {
        ages: [...tags.ages!],
        interests: [...tags.interests!],
        place: [...tags.place!],
        time: [...(tags.time ?? ["short", "medium"])],
      },
    };
  });
}

