export function computeCareerIndustryConsultingProfit(input: {
  consultingBillableHoursPerWeek?: number;
  averageHourlyRate?: number;
  fixedFeeProjectRevenue?: number;
  workshopRevenue?: number;
  retainerRevenue?: number;
  approvedExpenseReimbursements?: number;
  otherEarnedConsultingIncome?: number;
  phoneInternet?: number;
  schedulingVideoSoftware?: number;
  insurance?: number;
  legalAccountingFees?: number;
  continuingEducation?: number;
  advertisingNetworking?: number;
  unreimbursedTravel?: number;
  paymentFees?: number;
  officeEquipment?: number;
  otherExpenses?: number;
  billableDeliveryHours?: number;
  preparationResearchHours?: number;
  proposalSalesHours?: number;
  writtenDeliverableHours?: number;
  followUpRevisionHours?: number;
  travelHours?: number;
  marketingAdminHours?: number;
}): {
  weeklyHourlyRevenue: number;
  monthlyHourlyRevenue: number;
  grossServiceRevenue: number;
  totalExpenses: number;
  estimatedProfit: number;
  totalHours: number;
  profitPerHour: number | null;
  profitMarginPercent: number;
  utilizationPercent: number;
} {
  const weeklyHourlyRevenue =
    Math.max(0, Number(input.consultingBillableHoursPerWeek) || 0) *
    Math.max(0, Number(input.averageHourlyRate) || 0);
  const monthlyHourlyRevenue = weeklyHourlyRevenue * 4.33;
  const grossServiceRevenue =
    monthlyHourlyRevenue +
    Math.max(0, Number(input.fixedFeeProjectRevenue) || 0) +
    Math.max(0, Number(input.workshopRevenue) || 0) +
    Math.max(0, Number(input.retainerRevenue) || 0) +
    Math.max(0, Number(input.approvedExpenseReimbursements) || 0) +
    Math.max(0, Number(input.otherEarnedConsultingIncome) || 0);
  const totalExpenses =
    Math.max(0, Number(input.phoneInternet) || 0) +
    Math.max(0, Number(input.schedulingVideoSoftware) || 0) +
    Math.max(0, Number(input.insurance) || 0) +
    Math.max(0, Number(input.legalAccountingFees) || 0) +
    Math.max(0, Number(input.continuingEducation) || 0) +
    Math.max(0, Number(input.advertisingNetworking) || 0) +
    Math.max(0, Number(input.unreimbursedTravel) || 0) +
    Math.max(0, Number(input.paymentFees) || 0) +
    Math.max(0, Number(input.officeEquipment) || 0) +
    Math.max(0, Number(input.otherExpenses) || 0);
  const estimatedProfit = grossServiceRevenue - totalExpenses;
  const billableDeliveryHours = Math.max(0, Number(input.billableDeliveryHours) || 0);
  const totalHours =
    billableDeliveryHours +
    Math.max(0, Number(input.preparationResearchHours) || 0) +
    Math.max(0, Number(input.proposalSalesHours) || 0) +
    Math.max(0, Number(input.writtenDeliverableHours) || 0) +
    Math.max(0, Number(input.followUpRevisionHours) || 0) +
    Math.max(0, Number(input.travelHours) || 0) +
    Math.max(0, Number(input.marketingAdminHours) || 0);
  return {
    weeklyHourlyRevenue,
    monthlyHourlyRevenue,
    grossServiceRevenue,
    totalExpenses,
    estimatedProfit,
    totalHours,
    profitPerHour: totalHours > 0 ? estimatedProfit / totalHours : null,
    profitMarginPercent: grossServiceRevenue > 0 ? (estimatedProfit / grossServiceRevenue) * 100 : 0,
    utilizationPercent: totalHours > 0 ? (billableDeliveryHours / totalHours) * 100 : 0,
  };
}
